  REQUEST_CONTENT_TYPE_INVALID: 'REQUEST_CONTENT_TYPE_INVALID',
  ROUTE_NOT_FOUND: 'ROUTE_NOT_FOUND',
  MANYCHAT_SECRET_INVALID: 'MANYCHAT_SECRET_INVALID',
  ADMIN_TOKEN_INVALID: 'ADMIN_TOKEN_INVALID',
  ADMIN_TEMPORARILY_LOCKED: 'ADMIN_TEMPORARILY_LOCKED',
  LOCAL_RATE_LIMIT: 'LOCAL_RATE_LIMIT',
  SERVICE_NOT_CONFIGURED: 'SERVICE_NOT_CONFIGURED',
  CLAMI_COOLDOWN: 'CLAMI_COOLDOWN',
  CLAMI_DAILY_BUDGET: 'CLAMI_DAILY_BUDGET',
  CLAMI_MINUTE_BUDGET: 'CLAMI_MINUTE_BUDGET',
